import { PGlite } from "@electric-sql/pglite";
import { writeFile } from "node:fs/promises";
import { fixtureSql } from "./practice-fixtures.mjs";
import { loadAuthoringCatalog } from "./practice-content.mjs";
import { JUDGE_VERSION } from "./judge-content.mjs";

// Forward-only fix-up for ruins 1-5. The ruin 1-5 plain-language rewrite
// regenerated 20260904120000_all_ruin_fixtures.sql and
// 20260904180000_plain_language_question_copy.sql, but both are already tracked
// as applied on the live database, so `supabase db push` will not re-run them.
// Fresh DBs/CI are correct; the live DB still holds the old ruins 1-5
// (catalog_columns etc.). This migration re-applies exactly what the content
// pipeline produces for ruins 1-5 at dataset_version 2026-09-04.1, computing the
// expected rows with the same PGlite path used by scripts/judge-content.mjs.

const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => `${quote(JSON.stringify(value))}::jsonb`;
const RUINS = [1, 2, 3, 4, 5];

const questions = (await loadAuthoringCatalog()).filter((q) => RUINS.includes(q.id));
const db = new PGlite();
const statements = [
  "-- Generated by scripts/generate-replain-forward.mjs. Do not hand-edit computed rows.",
  "-- Forward-only fix-up: re-applies ruins 1-5 (allowed_tables, fixtures, expected",
  "-- rows/types, and private help incl. solution) at dataset_version 2026-09-04.1.",
  "-- Fresh DBs already receive this from 20260904120000; the live DB does not,",
  "-- because that version is tracked as applied and never re-runs on content change.",
  "begin;",
];
try {
  for (const q of questions) {
    statements.push(
      `update game_private.questions set allowed_tables = ${json(q.schema.map((t) => t.name))} where ruin_id = ${q.id} and dataset_version = ${quote(JUDGE_VERSION)};`,
    );
    statements.push(
      `update game_private.question_help set title = ${quote(q.title)}, description = ${quote(q.description)}, hints = ${json(q.hints)}, solution = ${quote(q.canonicalSolution)} where ruin_id = ${q.id} and dataset_version = ${quote(JUDGE_VERSION)};`,
    );
    statements.push(
      `delete from game_private.question_cases where ruin_id = ${q.id} and dataset_version = ${quote(JUDGE_VERSION)};`,
    );
    for (let i = 0; i < 3; i++) {
      const suffix = ["visible", "hidden_a", "hidden_b"][i];
      const schema = `fixture_r${String(q.id).padStart(2, "0")}_v20260904_1_${suffix}`;
      const sql = fixtureSql(q, i);
      await db.exec(`drop schema public cascade; create schema public; ${sql}`);
      const result = await db.query(q.canonicalSolution);
      const columns = result.fields.map((f) => f.name);
      const rows = result.rows.map((row) => columns.map((c) => row[c]));
      statements.push(`drop schema if exists ${schema} cascade;
create schema ${schema};
revoke all on schema ${schema} from public, anon, authenticated;
set search_path = ${schema}, pg_catalog;
${sql}
reset search_path;
revoke all on all tables in schema ${schema} from public, anon, authenticated;
grant usage on schema ${schema} to dilli_judge_executor;
grant select on all tables in schema ${schema} to dilli_judge_executor;
${q.schema.map((t) => `analyze ${schema}."${t.name}";`).join("\n")}
insert into game_private.question_cases
(ruin_id, case_id, fixture_schema, dataset_version, hidden, comparison, expected_columns, expected_rows, expected_types)
values (${q.id}, ${quote(`${JUDGE_VERSION}-${suffix}`)}, ${quote(schema)}, ${quote(JUDGE_VERSION)}, ${i > 0}, ${quote(q.ordered ? "ordered" : "unordered")}, ${json(columns)}, ${json(rows)}, ${json(result.fields.map((f) => f.dataTypeID))});`);
    }
  }
  statements.push("commit;");
  await writeFile(
    new URL("../supabase/migrations/20260906120000_replain_ruins_1_5.sql", import.meta.url),
    statements.join("\n\n") + "\n",
  );
  console.log("Generated forward fix-up for ruins 1-5 (20260906120000_replain_ruins_1_5.sql).");
} finally {
  await db.close();
}
